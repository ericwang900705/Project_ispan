package gameplatform.support.extension;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;
import java.nio.charset.StandardCharsets;
import java.util.*;
import org.junit.jupiter.api.*;
import org.springframework.core.io.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.SingleConnectionDataSource;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;
import gameplatform.support.service.SupportService;
import gameplatform.support.model.EventHub;

/** 執行遷移檔的同一份資料 DML，驗證分類編號、歷史關聯及重跑行為。 */
class SupportCategoryMigrationTests {
    SingleConnectionDataSource source; JdbcTemplate db; String core;
    @BeforeEach void setup() throws Exception {
        source=new SingleConnectionDataSource("jdbc:h2:mem:"+UUID.randomUUID()+";MODE=MSSQLServer;DATABASE_TO_LOWER=TRUE","sa","",true);
        db=new JdbcTemplate(source);db.execute("CREATE SCHEMA dbo");db.execute("SET SCHEMA dbo");
        db.execute("CREATE TABLE dbo.customer_service_categories(category_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,category_name NVARCHAR(50),description NVARCHAR(200))");
        db.execute("CREATE TABLE dbo.customer_service_tickets(ticket_id INT PRIMARY KEY,category_id INT REFERENCES dbo.customer_service_categories(category_id))");
        for(String name:List.of("帳號問題","遊戲問題","購買問題","其他問題")) db.update("INSERT INTO dbo.customer_service_categories(category_name) VALUES(?)",name);
        db.update("INSERT INTO dbo.customer_service_tickets VALUES(34,1)");
        String sql=new ClassPathResource("db/support-account-help.sql").getContentAsString(StandardCharsets.UTF_8);
        core=sql.substring(sql.indexOf("-- BEGIN CATEGORY DATA"),sql.indexOf("-- END CATEGORY DATA"));
    }
    @AfterEach void close(){source.destroy();}
    void migrate(){new ResourceDatabasePopulator(new ByteArrayResource(core.getBytes(StandardCharsets.UTF_8))).execute(source);}
    String name(int id){return db.queryForObject("SELECT category_name FROM dbo.customer_service_categories WHERE category_id=?",String.class,id);}
    @Test void initializesEightCategoriesWithoutChangingHistoricalIds(){
        migrate();assertEquals("帳號與登入",name(1));assertEquals("訂單問題",name(3));
        assertEquals(8,db.queryForObject("SELECT COUNT(*) FROM dbo.customer_service_categories",Integer.class));
        assertEquals(1,db.queryForObject("SELECT category_id FROM dbo.customer_service_tickets WHERE ticket_id=34",Integer.class));
    }
    @Test void repeatedStartupDoesNotDuplicateCategories(){migrate();migrate();assertEquals(8,db.queryForObject("SELECT COUNT(*) FROM dbo.customer_service_categories",Integer.class));}
    @Test void preservesCustomCategoriesAndDescriptions(){
        db.update("INSERT INTO dbo.customer_service_categories(category_name,description) VALUES('特殊問題','自訂說明')");
        db.update("UPDATE dbo.customer_service_categories SET description='既有說明' WHERE category_id=2");migrate();
        assertEquals(9,db.queryForObject("SELECT COUNT(*) FROM dbo.customer_service_categories",Integer.class));
        assertEquals("既有說明",db.queryForObject("SELECT description FROM dbo.customer_service_categories WHERE category_id=2",String.class));
    }
    @Test void canonicalAndLegacyRowsAreBothPreservedWhenTheyAlreadyCoexist(){
        db.update("INSERT INTO dbo.customer_service_categories(category_name) VALUES('帳號與登入')");migrate();
        assertEquals("帳號問題",name(1));assertEquals(1,db.queryForObject("SELECT category_id FROM dbo.customer_service_tickets WHERE ticket_id=34",Integer.class));
        assertEquals(1,db.queryForObject("SELECT COUNT(*) FROM dbo.customer_service_categories WHERE category_name='帳號與登入'",Integer.class));
    }
    @Test void categoryApiReturnsDescriptionsInBusinessOrder(){
        migrate();var rows=new SupportService(db,mock(EventHub.class),"h2").categories();
        assertEquals(List.of("帳號與登入","遊戲問題","訂單問題","付款問題","退款問題","優惠券問題","網站操作異常","其他問題"),rows.stream().map(r->r.get("name")).toList());
        assertTrue(rows.stream().allMatch(r->r.get("description")!=null));
    }
}
