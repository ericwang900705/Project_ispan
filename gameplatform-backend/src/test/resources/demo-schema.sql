CREATE TABLE members (
    member_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username NVARCHAR(100) NOT NULL,
    is_publisher BIT NOT NULL DEFAULT FALSE
);

CREATE TABLE admin (
    admin_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_account NVARCHAR(100) NOT NULL
);

CREATE TABLE games (
    game_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_name NVARCHAR(200) NOT NULL,
    member_id INT REFERENCES members(member_id),
    price DECIMAL(10,2) NOT NULL DEFAULT 0,
    description NVARCHAR(4000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    release_date TIMESTAMP,
    cover_url VARCHAR(500),
    pending_review_type VARCHAR(20),
    review_requested_at TIMESTAMP,
    review_request_reason NVARCHAR(500),
    pending_request_key VARCHAR(36),
    off_shelf_source VARCHAR(20),
    off_shelf_at BIGINT,
    restore_until BIGINT,
    off_shelf_previous_status VARCHAR(20),
    off_shelf_reason NVARCHAR(500),
    off_shelf_admin_id INT REFERENCES admin(admin_id),
    UNIQUE(game_name),
    CHECK(price>=0),
    CHECK((CASE WHEN status='DRAFT' THEN 1 WHEN status='PUBLISHED' THEN 1 WHEN status='COMING_SOON' THEN 1 WHEN status='OFF_SHELF' THEN 1 ELSE 0 END = 1)),
    CHECK(pending_review_type IS NULL OR (CASE WHEN pending_review_type='PUBLISH' THEN 1 WHEN pending_review_type='OFF_SHELF' THEN 1 ELSE 0 END = 1))
);

CREATE TABLE customer_service_categories (
    category_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name NVARCHAR(50) NOT NULL UNIQUE,
    description NVARCHAR(200)
);

CREATE SEQUENCE customer_service_ticket_no_seq AS BIGINT START WITH 1;

CREATE TABLE customer_service_tickets (
    ticket_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_no VARCHAR(30) NOT NULL UNIQUE,
    member_id INT NOT NULL REFERENCES members(member_id),
    category_id INT NOT NULL REFERENCES customer_service_categories(category_id),
    game_id INT REFERENCES games(game_id),
    subject NVARCHAR(100) NOT NULL,
    content NVARCHAR(8000) NOT NULL,
    priority VARCHAR(10) DEFAULT 'NORMAL' NOT NULL CHECK((CASE WHEN priority='URGENT' THEN 1 WHEN priority='HIGH' THEN 1 WHEN priority='NORMAL' THEN 1 WHEN priority='LOW' THEN 1 ELSE 0 END)=1),
    status VARCHAR(20) DEFAULT 'OPEN' NOT NULL CHECK((CASE WHEN status='OPEN' THEN 1 WHEN status='IN_PROGRESS' THEN 1 WHEN status='CLOSED' THEN 1 ELSE 0 END = 1)),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    admin_id INT REFERENCES admin(admin_id),
    UNIQUE(ticket_id,member_id)
);

CREATE TABLE customer_service_messages (
    message_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id INT NOT NULL REFERENCES customer_service_tickets(ticket_id),
    sender_member_id INT REFERENCES members(member_id),
    message_content NVARCHAR(4000) NOT NULL,
    sent_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    sender_type VARCHAR(10) NOT NULL,
    admin_id INT REFERENCES admin(admin_id),
    CHECK((sender_type='MEMBER' AND sender_member_id IS NOT NULL AND admin_id IS NULL) OR (sender_type='ADMIN' AND sender_member_id IS NULL AND admin_id IS NOT NULL)),
    FOREIGN KEY(ticket_id,sender_member_id) REFERENCES customer_service_tickets(ticket_id,member_id)
);

CREATE TABLE chat_rooms (
    support_room_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id INT NOT NULL REFERENCES members(member_id),
    status VARCHAR(20) DEFAULT 'OPEN' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    closed_at TIMESTAMP,
    admin_id INT REFERENCES admin(admin_id),
    ticket_id INT REFERENCES customer_service_tickets(ticket_id),
    open_member_id INT GENERATED ALWAYS AS (CASE WHEN status='OPEN' THEN member_id ELSE NULL END),
    UNIQUE NULLS DISTINCT(open_member_id),
    UNIQUE(support_room_id,member_id),
    FOREIGN KEY(ticket_id,member_id) REFERENCES customer_service_tickets(ticket_id,member_id),
    CHECK((status='OPEN' AND closed_at IS NULL AND ticket_id IS NULL) OR (status='CLOSED' AND closed_at IS NOT NULL))
);

CREATE TABLE chat_messages (
    support_message_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    support_room_id INT NOT NULL REFERENCES chat_rooms(support_room_id),
    member_id INT REFERENCES members(member_id),
    admin_id INT REFERENCES admin(admin_id),
    sender_type VARCHAR(10) NOT NULL,
    content NVARCHAR(4000) NOT NULL,
    sent_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CHECK((sender_type='MEMBER' AND member_id IS NOT NULL AND admin_id IS NULL) OR (sender_type='ADMIN' AND member_id IS NULL AND admin_id IS NOT NULL)),
    FOREIGN KEY(support_room_id,member_id) REFERENCES chat_rooms(support_room_id,member_id)
);

CREATE INDEX IX_chat_message_parent ON chat_messages(support_room_id,support_message_id);

CREATE INDEX IX_service_message_parent ON customer_service_messages(ticket_id,message_id);

CREATE TABLE customer_service_attachments (
    attachment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id INT NOT NULL REFERENCES customer_service_messages(message_id),
    file_name NVARCHAR(120) NOT NULL,
    content_type VARCHAR(20) NOT NULL CHECK((CASE WHEN content_type='image/jpeg' THEN 1 WHEN content_type='image/png' THEN 1 ELSE 0 END = 1)),
    size_bytes INT NOT NULL CHECK(size_bytes BETWEEN 1 AND 5242880),
    width INT NOT NULL CHECK(width BETWEEN 1 AND 4096),
    height INT NOT NULL CHECK(height BETWEEN 1 AND 4096),
    image_data BINARY LARGE OBJECT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX IX_csa_message ON customer_service_attachments(message_id,attachment_id);

CREATE TABLE customer_service_ticket_games (
    ticket_id INT NOT NULL,
    game_id INT NOT NULL,
    sort_order INT NOT NULL DEFAULT (0),
    CONSTRAINT PK_customer_service_ticket_games PRIMARY KEY (ticket_id, game_id),
    CONSTRAINT FK_cstg_ticket FOREIGN KEY (ticket_id) REFERENCES customer_service_tickets(ticket_id),
    CONSTRAINT FK_cstg_game FOREIGN KEY (game_id) REFERENCES games(game_id),
    CONSTRAINT CK_cstg_sort CHECK (sort_order >= 0)
);

